/**
 * Starts Metro for the dev client against the STAGING project.
 *
 * Setting EXPO_PUBLIC_* in the environment is not enough: in dev, Expo's virtual env
 * module merges the .env files over process.env, so `.env` (production) would win for
 * every key it defines while staging-only keys still apply. The later .env.local wins
 * over .env, so we write the public staging values there while Metro runs and remove
 * the file on exit. Secrets used only by the scripts (service-role key, persona
 * password) are never written or passed to Metro.
 */
import { spawn } from 'child_process';
import fs from 'fs';
import path from 'path';
import { REPO_ROOT, loadStagingEnv } from './stagingEnv';

const SCRIPT_ONLY_VARS = new Set(['SUPABASE_SERVICE_ROLE_KEY', 'TEST_PERSONA_PASSWORD']);

const ENV_OVERRIDE_FILE = path.join(REPO_ROOT, '.env.local');
const ENV_OVERRIDE_MARKER = '# Generated by npm run start:staging; removed when Metro exits. Safe to delete.';
// These merge after .env.local, so they would beat the staging values.
const LATER_ENV_FILES = ['.env.development.local'];

export const buildEnvOverride = (values: Record<string, string>) =>
  [
    ENV_OVERRIDE_MARKER,
    ...Object.entries(values)
      .filter(([key]) => key.startsWith('EXPO_PUBLIC_') && !SCRIPT_ONLY_VARS.has(key))
      .map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n');

const writeEnvOverride = (values: Record<string, string>) => {
  const later = LATER_ENV_FILES.find((file) => fs.existsSync(path.join(REPO_ROOT, file)));
  if (later) {
    throw new Error(`${later} would override the staging values. Move it aside and try again.`);
  }
  if (
    fs.existsSync(ENV_OVERRIDE_FILE) &&
    !fs.readFileSync(ENV_OVERRIDE_FILE, 'utf8').startsWith(ENV_OVERRIDE_MARKER)
  ) {
    throw new Error('.env.local exists and was not created by this script. Move it aside and try again.');
  }
  fs.writeFileSync(ENV_OVERRIDE_FILE, buildEnvOverride(values));
};

const removeEnvOverride = () => {
  fs.rmSync(ENV_OVERRIDE_FILE, { force: true });
};

export const main = async (args: string[]) => {
  const env = loadStagingEnv();
  const childEnv: NodeJS.ProcessEnv = { ...process.env };
  Object.entries(env.raw).forEach(([key, value]) => {
    if (!SCRIPT_ONLY_VARS.has(key)) childEnv[key] = value;
  });
  childEnv.EXPO_PUBLIC_APP_ENV = childEnv.EXPO_PUBLIC_APP_ENV || 'staging';

  writeEnvOverride({ ...env.raw, EXPO_PUBLIC_APP_ENV: childEnv.EXPO_PUBLIC_APP_ENV });
  process.on('exit', removeEnvOverride);

  console.log(`Starting Metro against staging (${env.url}).`);
  console.log(`Fake Health data: ${childEnv.EXPO_PUBLIC_FAKE_HEALTH === 'true' ? 'on' : 'off'}\n`);

  // --clear: EXPO_PUBLIC_* values are inlined at bundle time, so a cached bundle
  // could still point at the previous backend.
  const child = spawn('npx', ['expo', 'start', '--dev-client', '--clear', ...args], {
    cwd: REPO_ROOT,
    env: childEnv,
    stdio: 'inherit',
  });
  (['SIGINT', 'SIGTERM', 'SIGHUP'] as const).forEach((signal) => {
    process.on(signal, () => child.kill(signal));
  });
  await new Promise<void>((resolve, reject) => {
    child.on('exit', (code) => (code === 0 || code === null ? resolve() : reject(new Error(`expo exited with ${code}`))));
    child.on('error', reject);
  });
};
